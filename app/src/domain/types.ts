import type { MascotConfig } from '../../../design-system/assets/maskot/mascot.mjs';

export type Language = 'id' | 'en';
export type Localized = { ar: string; id: string; en: string };
export type Vocabulary = Localized & { idKey: string; symbol: string };
export type ActivityKind = 'vocabulary' | 'pattern' | 'dialogue' | 'reading' | 'practice' | 'quiz';
export type Activity = { id: string; kind: ActivityKind; title: Localized; session?: number; words?: Vocabulary[] };
export type Choice = { id: string; text: string; lang: 'ar' | Language };
export type Question = {
  id: string;
  kind: 'study' | 'choice' | 'order' | 'speak' | 'listen';
  prompt: Localized;
  text?: Localized;
  word?: Vocabulary;
  speaker?: string;
  choices?: Choice[];
  answer?: string;
  words?: string[];
  orderAlternatives?: string[];
  meaningTest?: boolean;
  reading?: Localized;
};
export type Unit = {
  id: number;
  curriculum?: 'shaharil';
  title: Localized;
  subtitle: Localized;
  words: Vocabulary[];
  patterns: { words: string[]; translation: Omit<Localized, 'ar'> }[];
  dialogue: (Localized & { speaker?: string })[];
  reading: Localized;
  comprehension: { prompt: Localized; choices: string[]; answer: number }[];
};
export type Answer = { questionId: string; correct: boolean; skipped: boolean; hinted: boolean; wordId?: string };
export type QuestionVersion = 1 | 2;
export type Session = { unitId: number; activityId: string; questionVersion?: QuestionVersion; cursor: number; answers: Answer[]; hintAt: number | null };
export type ReviewEntry = { reason: 'incorrect' | 'speech-skipped'; failures: number; lastAttemptDay: string };
export type ReviewSession = { questionIds: string[]; cursor: number; answers: Answer[] };
export type Profile = {
  version: 1;
  curriculum?: 'shaharil';
  language: Language;
  onboarded: boolean;
  mascot: MascotConfig;
  theme: 'system' | 'light' | 'dark';
  translation: boolean;
  sound: boolean;
  dates: number;
  xp: number;
  activityDays: string[];
  hintDay: string;
  hintsUsed: number;
  hintsPurchased: number;
  ownedAnimals: string[];
  ownedSkins: string[];
  ownedItems: string[];
  completedActivities: string[];
  creditedQuestions: string[];
  mastery: Record<string, number>;
  bestScores: Record<string, number>;
  rewardedUnits: number[];
  chestRewards: Record<string, string>;
  session: Session | null;
  savedSessions: Record<string, Session>;
  reviews: Record<string, ReviewEntry>;
  reviewSession: ReviewSession | null;
};
